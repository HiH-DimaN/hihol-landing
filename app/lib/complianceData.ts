// Plural helper for the self-check result ("1 признак", "2 признака", "5 признаков").
export function pluralPriznak(n: number): string {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return 'признак'
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return 'признака'
  return 'признаков'
}
